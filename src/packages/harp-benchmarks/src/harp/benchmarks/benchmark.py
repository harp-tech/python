import argparse
import platform
import sys
from dataclasses import dataclass
from pathlib import Path
from statistics import mean, stdev
from time import perf_counter
from typing import Callable

import numpy as np
import pandas as pd
from harp.benchmarks._registers import (
    BENCHMARK_REGISTERS,
    DATA_DIR,
    REPORT_PATH,
    BenchmarkedRegister,
)
from harp.benchmarks.generate import ensure_corpus
from harp.data import parse_to_dataframe

_MIB = 1024**2


@dataclass
class TimingStats:
    """Per-run timings (seconds) and throughput derived from the mean."""

    min: float
    mean: float
    max: float
    stdev: float
    frames: int
    file_bytes: int

    @property
    def mframes_per_s(self) -> float:
        return (self.frames / self.mean) / 1e6

    @property
    def mib_per_s(self) -> float:
        return (self.file_bytes / self.mean) / _MIB


def _time(fn: Callable[[], object], *, runs: int, frames: int, file_bytes: int) -> TimingStats:
    fn()  # warm-up for imports, caches and first-touch pages, not measured
    samples: list[float] = []
    for _ in range(runs):
        t0 = perf_counter()
        fn()
        samples.append(perf_counter() - t0)
    return TimingStats(
        min=min(samples),
        mean=mean(samples),
        max=max(samples),
        stdev=stdev(samples) if len(samples) > 1 else 0.0,
        frames=frames,
        file_bytes=file_bytes,
    )


@dataclass
class RegisterResult:
    name: str
    address: int
    frames: int
    stride: int
    payload_bytes: int
    file_bytes: int
    bulk_preread: TimingStats
    bulk_reread: TimingStats
    cols: TimingStats
    df_preread: TimingStats
    df_reread: TimingStats


def _dataset_info(raw: bytes, payload_bytes: int) -> tuple[int, int]:
    data = np.frombuffer(raw, dtype=np.uint8)
    stride = int(data[1]) + 2
    nrows = len(data) // stride
    return nrows, stride


def benchmark_register(reg: BenchmarkedRegister, path: Path, *, runs: int) -> RegisterResult:
    register = reg.register
    raw = path.read_bytes()
    file_bytes = len(raw)
    payload_bytes = register.payload_class.payload_dtype.itemsize
    frames, stride = _dataset_info(raw, payload_bytes)

    bulk_pre = _time(
        lambda: register.parse_bulk(raw, parse_timestamp=True),
        runs=runs,
        frames=frames,
        file_bytes=file_bytes,
    )
    bulk_re = _time(
        lambda: register.parse_bulk(path.read_bytes(), parse_timestamp=True),
        runs=runs,
        frames=frames,
        file_bytes=file_bytes,
    )
    # Decode only: pre-parse the bulk views once, then time payload_as_columns() alone,
    # this is where the decode_batch of every converter runs, with no file read and no
    # pandas DataFrame construction. Matches the decode options of parse_to_dataframe.
    _, _, _, payload = register.parse_bulk(raw, parse_timestamp=True)
    cols = _time(
        lambda: payload.payload_as_columns(decode_enums=True, demux_bit_masks=False),
        runs=runs,
        frames=frames,
        file_bytes=file_bytes,
    )
    df_pre = _time(
        lambda: parse_to_dataframe(register, raw, time_index=reg.timestamped),
        runs=runs,
        frames=frames,
        file_bytes=file_bytes,
    )
    df_re = _time(
        lambda: parse_to_dataframe(register, path.read_bytes(), time_index=reg.timestamped),
        runs=runs,
        frames=frames,
        file_bytes=file_bytes,
    )

    return RegisterResult(
        name=reg.name,
        address=reg.address,
        frames=frames,
        stride=stride,
        payload_bytes=payload_bytes,
        file_bytes=file_bytes,
        bulk_preread=bulk_pre,
        bulk_reread=bulk_re,
        cols=cols,
        df_preread=df_pre,
        df_reread=df_re,
    )


def _fmt_ms(s: float) -> str:
    return f"{s * 1e3:.2f}"


def build_report(results: list[RegisterResult], *, runs: int) -> str:
    lines: list[str] = []
    lines.append("# Harp parsing benchmark\n")
    lines.append(
        "Parsing throughput for every register in `harp.benchmarks.register_models`, "
        "measured over binary protocol log files generated by `harp.benchmarks.generate`.\n"
    )

    # Environment
    lines.append("## Environment\n")
    lines.append("| Key | Value |")
    lines.append("| --- | --- |")
    lines.append(f"| Platform | {platform.platform()} |")
    lines.append(f"| Python | {sys.version.split()[0]} |")
    lines.append(f"| NumPy | {np.__version__} |")
    lines.append(f"| pandas | {pd.__version__} |")
    lines.append(f"| Runs per measurement | {runs} |")
    lines.append(
        "| Measured op | one full-file parse; min/mean/stdev over runs (1 warm-up discarded) |\n"
    )

    # Dataset summary
    lines.append("## Datasets\n")
    lines.append("| Register | Addr | Frames | Payload (B) | Frame/stride (B) | File (MiB) |")
    lines.append("| --- | ---: | ---: | ---: | ---: | ---: |")
    for r in results:
        lines.append(
            f"| {r.name} | {r.address} | {r.frames:,} | {r.payload_bytes} | "
            f"{r.stride} | {r.file_bytes / _MIB:.1f} |"
        )
    lines.append("")

    def _table(
        title: str,
        note: str,
        pick: Callable[[RegisterResult], tuple[TimingStats, TimingStats]],
    ) -> None:
        lines.append(f"## {title}\n")
        lines.append(f"{note}\n")
        lines.append(
            "| Register | Frames | pre mean (ms) | pre min (ms) | pre Mframes/s | pre MiB/s "
            "| re mean (ms) | re Mframes/s | re MiB/s |"
        )
        lines.append("| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
        for r in results:
            pre, re = pick(r)
            lines.append(
                f"| {r.name} | {r.frames:,} | {_fmt_ms(pre.mean)} | {_fmt_ms(pre.min)} | "
                f"{pre.mframes_per_s:.2f} | {pre.mib_per_s:,.0f} | "
                f"{_fmt_ms(re.mean)} | {re.mframes_per_s:.2f} | {re.mib_per_s:,.0f} |"
            )
        lines.append("")

    _table(
        "`parse_bulk` (core zero-copy parse)",
        "`pre` = parse a pre-read buffer; `re` = re-read the file from disk each run. "
        "Note `parse_bulk` only builds lazy strided views and does **not** run "
        "converters, so timings are near-uniform regardless of payload shape.",
        lambda r: (r.bulk_preread, r.bulk_reread),
    )
    _table(
        "`parse_to_dataframe` (full path to pandas, copy=False)",
        "`pre` = parse a pre-read buffer; `re` = read file + parse each run.",
        lambda r: (r.df_preread, r.df_reread),
    )

    # Decode-only table (single mode): payload_as_columns() runs the converter of every field,
    # converter.decode_batch, with no file read and no pandas construction.
    lines.append("## `payload_as_columns`, decode only, where converters run\n")
    lines.append(
        "Isolates the decode step: `parse_bulk` views are built once up front, then "
        "only `payload.payload_as_columns()` is timed. This is where the "
        "`converter.decode_batch` executes. Registers whose converters loop in Python "
        "(`HarpVersionConverter`, `StringConverter`, `BytesToIntConverter` -> object "
        "dtype) dominate here; vectorized converters stay cheap.\n"
    )
    lines.append("| Register | Frames | mean (ms) | min (ms) | stdev (ms) | Mframes/s | MiB/s |")
    lines.append("| --- | ---: | ---: | ---: | ---: | ---: | ---: |")
    for r in results:
        c = r.cols
        lines.append(
            f"| {r.name} | {r.frames:,} | {_fmt_ms(c.mean)} | {_fmt_ms(c.min)} | "
            f"{_fmt_ms(c.stdev)} | {c.mframes_per_s:.2f} | {c.mib_per_s:,.0f} |"
        )
    lines.append("")

    # Decomposition: parse_to_dataframe(pre) is about parse_bulk(pre) + payload_as_columns + pandas.
    lines.append("## Decomposition (pre-read means, ms)\n")
    lines.append(
        "`parse_to_dataframe` is approximately `parse_bulk` to build views, plus "
        "`payload_as_columns` to decode, plus "
        "pandas DataFrame construction. The residual column is `df - bulk - payload_as_columns`, "
        "i.e. the pandas/column-assembly overhead. Note the three terms are timed in "
        "separate loops, so for converter-dominated registers (large mean, large stdev) "
        "the residual is within noise and can even go slightly negative.\n"
    )
    lines.append(
        "| Register | parse_bulk | payload_as_columns | parse_to_dataframe | pandas residual |"
    )
    lines.append("| --- | ---: | ---: | ---: | ---: |")
    for r in results:
        residual = r.df_preread.mean - r.bulk_preread.mean - r.cols.mean
        lines.append(
            f"| {r.name} | {_fmt_ms(r.bulk_preread.mean)} | {_fmt_ms(r.cols.mean)} | "
            f"{_fmt_ms(r.df_preread.mean)} | {_fmt_ms(residual)} |"
        )
    lines.append("")

    return "\n".join(lines)


def _select(only):
    selected = BENCHMARK_REGISTERS
    if only:
        wanted = set(only)
        selected = [r for r in BENCHMARK_REGISTERS if r.name in wanted]
        missing = wanted - {r.name for r in selected}
        if missing:
            raise SystemExit(f"Unknown register name(s): {', '.join(sorted(missing))}")
    return selected


def _prepare_corpora(selected, *, entries: int, force: bool, data_dir: Path) -> None:
    """Generate any missing corpora (cache honored unless ``force``), printing progress."""
    data_dir.mkdir(parents=True, exist_ok=True)
    n = len(selected)
    mode = "rebuilding" if force else "cache honored"
    print(f"Preparing {n} corpus file(s) in {data_dir} ({mode}, {entries:,} frames each):")
    for i, reg in enumerate(selected, 1):
        print(f"  [{i}/{n}] {reg.name:<24s} ", end="", flush=True)
        _, generated = ensure_corpus(reg, entries, force=force, data_dir=data_dir)
        print("generated" if generated else "cached")
    print()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--runs", type=int, default=10, help="repeats per measurement (default: 10)"
    )
    parser.add_argument(
        "--entries",
        type=int,
        default=1_000_000,
        help="frames per corpus when generating (default: 1,000,000)",
    )
    parser.add_argument(
        "--force", action="store_true", help="regenerate corpora even if cached files exist"
    )
    parser.add_argument(
        "--only", nargs="+", metavar="NAME", help="restrict to these register names (default: all)"
    )
    parser.add_argument(
        "--dir",
        type=Path,
        default=DATA_DIR,
        help=f"directory containing/receiving corpus files (default: {DATA_DIR})",
    )
    parser.add_argument("--report", type=Path, default=REPORT_PATH)
    parser.add_argument(
        "--head",
        action="store_true",
        help="print head(5) of the DataFrame of each register to stdout (not saved to the report)",
    )
    args = parser.parse_args()

    selected = _select(args.only)

    # Ensure the data exists before benchmarking (honor the cache unless --force).
    _prepare_corpora(selected, entries=args.entries, force=args.force, data_dir=args.dir)

    n = len(selected)
    results: list[RegisterResult] = []
    print(f"Benchmarking {n} register(s), {args.runs} runs each:")
    for i, reg in enumerate(selected, 1):
        path = args.dir / reg.filename
        print(f"  [{i}/{n}] {reg.name:<24s} ", end="", flush=True)
        res = benchmark_register(reg, path, runs=args.runs)
        results.append(res)
        print(
            f"bulk={_fmt_ms(res.bulk_preread.mean):>8s}ms "
            f"payload_as_columns={_fmt_ms(res.cols.mean):>9s}ms "
            f"df={_fmt_ms(res.df_preread.mean):>9s}ms"
        )
        if args.head:
            df = parse_to_dataframe(reg.register, path.read_bytes(), time_index=True)
            print(df.head(5))
            print()

    args.report.parent.mkdir(parents=True, exist_ok=True)
    report = build_report(results, runs=args.runs)
    args.report.write_text(report, encoding="utf-8")
    print(f"\nReport written to {args.report}")


if __name__ == "__main__":
    main()
